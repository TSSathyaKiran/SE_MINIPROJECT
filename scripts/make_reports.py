"""Write the test reports in docs/reports/ from one run of the CI tests:

    pip install -r requirements.txt        (needs pytest-cov)
    python scripts/make_reports.py

Runs the same tests as CI (tests/ui, tests/performance and tests/security need other
tools and are left out) with line and branch coverage (settings in .coveragerc), then
writes:
    docs/reports/Unit_Test_Report.md               every test, its level and result
    docs/reports/Code_Coverage_Report.md           statement coverage per file, lines not run
    docs/reports/Branch_Coverage_Report.md         branch coverage per file, branches not taken
    docs/reports/results/pytest-coverage-run.txt   the pytest and coverage output
The exit code is pytest's, so a failing test is never hidden.
"""
import ast
import json
import os
import platform
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import date
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reports"
CI_ARGS = ["tests", "--ignore=tests/ui", "--ignore=tests/performance", "--ignore=tests/security"]
CI_COMMAND = "pytest -q " + " ".join(CI_ARGS)
API_FIXTURES = {"client", "login_as"}         # tests that send requests through Flask
SYSTEM_FILES = {"tests/test_system.py"}       # tests that use the app over real HTTP
LEVELS = ["Unit", "API", "System"]
RESULTS = ["passed", "failed", "error", "skipped"]


def run_tests(tmp):
    """Run the CI tests with coverage. Returns (exit code, output, junit path, json path)."""
    junit, cov_json = tmp / "junit.xml", tmp / "coverage.json"
    cmd = [sys.executable, "-m", "pytest", "-q", "-o", "addopts=", *CI_ARGS, "--cov",
           "--cov-report=term-missing", f"--cov-report=json:{cov_json}", f"--junitxml={junit}"]
    env = {**os.environ, "COVERAGE_FILE": str(tmp / ".coverage")}
    proc = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True)
    lines = [line.replace(f"{ROOT}/", "") for line in (proc.stdout + proc.stderr).splitlines()
             if str(tmp) not in line]
    return proc.returncode, "\n".join(lines) + "\n", junit, cov_json


def case_ids(names, docstring=""):
    """Test case ids named in test names (test_tc_grd_01_...) or a docstring (TC-Grd-01)."""
    found = {f"TC-{'UX' if area == 'ux' else area.title()}-{n}"
             for name in names for area, n in re.findall(r"tc_([a-z]+)_(\d{2})", name)}
    found |= set(re.findall(r"TC-[A-Za-z]+-\d{2}", docstring))
    return sorted(found)


def test_files():
    """{file: (module docstring, {test function: level})} for every CI test file."""
    files = {}
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        rel = path.relative_to(ROOT).as_posix()
        tree = ast.parse(path.read_text())
        levels = {}
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                args = {a.arg for a in node.args.args}
                levels[node.name] = ("System" if rel in SYSTEM_FILES
                                     else "API" if args & API_FIXTURES else "Unit")
        files[rel] = (ast.get_docstring(tree) or "", levels)
    return files


def read_junit(path, files):
    """One dict per test: file, name, level, result, seconds."""
    suite = ET.parse(path).getroot()
    suite = suite if suite.tag == "testsuite" else suite.find("testsuite")
    tests = []
    for case in suite.iter("testcase"):
        file = case.get("classname").replace(".", "/") + ".py"
        name = case.get("name")
        result = "passed"
        for tag, label in [("failure", "failed"), ("error", "error"), ("skipped", "skipped")]:
            if case.find(tag) is not None:
                result = label
        level = files.get(file, ("", {}))[1].get(name.split("[")[0], "Unit")
        tests.append({"file": file, "name": name, "level": level, "result": result,
                      "seconds": float(case.get("time") or 0)})
    return tests, float(suite.get("time") or 0)


def build_info():
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                         capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT,
                           capture_output=True, text=True).stdout.strip()
    return f"commit `{sha}`" + (" plus uncommitted changes" if dirty else "")


def header(title, purpose, build):
    return [f"# {title}", "",
            f"Generated by `python scripts/make_reports.py` on {date.today().isoformat()}; "
            "do not edit by hand, run the script again.", "",
            f"- **Purpose:** {purpose}",
            f"- **Code:** {build}",
            f"- **Command:** `{CI_COMMAND}` with coverage (the same tests CI runs)",
            f"- **Environment:** Python {platform.python_version()}, pytest {version('pytest')}, "
            f"pytest-cov {version('pytest-cov')}, coverage.py {version('coverage')}, "
            f"{platform.system()} {platform.machine()}; in-memory SQLite. CI runs the same "
            "tests on Python 3.11, Ubuntu.", ""]


def pct(part, whole):
    return f"{part * 100 / whole:.1f}%" if whole else "n/a"


def unit_report(tests, seconds, files, build):
    count = lambda rows, result: sum(1 for t in rows if t["result"] == result)
    lines = header("Unit Test Report",
                   "results of the automated pytest suite (unit, API and system tests).", build)
    lines += ["## Summary", "",
              "| Tests | Passed | Failed | Errors | Skipped | Run time |",
              "| --- | --- | --- | --- | --- | --- |",
              f"| {len(tests)} | " + " | ".join(str(count(tests, r)) for r in RESULTS)
              + f" | {seconds:.1f} s |", "",
              "## By level", "",
              "| Level | What the tests do | Tests | Passed |", "| --- | --- | --- | --- |"]
    meaning = {"Unit": "call rule functions, scripts or settings directly (no HTTP request)",
               "API": "send requests through Flask's test client to the API and pages, "
                      "with a fresh in-memory database per test",
               "System": "start the app on a local port with the demo data and use it over "
                         "real HTTP (`tests/test_system.py`)"}
    for level in LEVELS:
        rows = [t for t in tests if t["level"] == level]
        lines.append(f"| {level} | {meaning[level]} | {len(rows)} | {count(rows, 'passed')} |")

    by_file = defaultdict(list)
    for t in tests:
        by_file[t["file"]].append(t)
    lines += ["", "## By test file", "",
              "| File | Tests | Passed | Failed | Skipped | Unit / API / System | Test cases |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for file, rows in sorted(by_file.items()):
        split = " / ".join(str(sum(1 for t in rows if t["level"] == lv)) for lv in LEVELS)
        cases = case_ids([t["name"] for t in rows], files.get(file, ("",))[0])
        failed = count(rows, "failed") + count(rows, "error")
        lines.append(f"| `{file}` | {len(rows)} | {count(rows, 'passed')} | {failed} | "
                     f"{count(rows, 'skipped')} | {split} | {', '.join(cases) or '-'} |")
    lines += ["", "Test cases are taken from the test names (`test_tc_<area>_<nn>_...`) and the "
              "file's docstring. The specifications are in `docs/Test_Plan/Test_Cases.md`.", "",
              "## Every test", ""]
    for file, rows in sorted(by_file.items()):
        lines += [f"<details><summary><code>{file}</code>: {count(rows, 'passed')} of "
                  f"{len(rows)} passed</summary>", "",
                  "| Test | Level | Result | Time |", "| --- | --- | --- | --- |"]
        lines += [f"| `{t['name']}` | {t['level']} | {t['result']} | {t['seconds']:.3f} s |"
                  for t in rows]
        lines += ["", "</details>", ""]
    return "\n".join(lines)


def source_lines(file):
    return (ROOT / file).read_text().splitlines()


def snippet(code, line):
    text = code[line - 1].strip() if 0 < line <= len(code) else ""
    text = text if len(text) <= 70 else text[:67] + "..."
    return f"`{text}`" if text else ""


def scopes(files):
    """Application code first, then the command-line scripts, each sorted by path."""
    app = sorted(f for f in files if f.startswith("src/app/"))
    return [("Application (`src/app/`)", app),
            ("Scripts (`src/*.py`, `scripts/`)", sorted(f for f in files if f not in app))]


def totals(files, names):
    keys = ["num_statements", "covered_lines", "missing_lines", "num_branches",
            "covered_branches", "missing_branches", "num_partial_branches"]
    return {k: sum(files[n]["summary"][k] for n in names) for k in keys}


def coverage_header(title, purpose, build):
    lines = header(title, purpose, build)
    lines[-1:-1] = [f"- **Measured:** every Python file in `src/` and `scripts/`; settings in "
                    "`.coveragerc`. The `if __name__ == \"__main__\":` blocks that only start a "
                    "script from the command line are left out."]
    return lines


def line_report(cov, build):
    files = cov["files"]
    lines = coverage_header("Code Coverage Report",
                            "how much of the code the automated tests run (statement coverage).",
                            build)
    lines += ["## Summary", "",
              "| Scope | Statements | Run | Not run | Line coverage | Line + branch |",
              "| --- | --- | --- | --- | --- | --- |"]
    every = []
    for label, names in scopes(files):
        every += names
        t = totals(files, names)
        both = pct(t["covered_lines"] + t["covered_branches"], t["num_statements"] + t["num_branches"])
        lines.append(f"| {label} | {t['num_statements']} | {t['covered_lines']} | "
                     f"{t['missing_lines']} | {pct(t['covered_lines'], t['num_statements'])} | {both} |")
    t = totals(files, every)
    lines.append(f"| **Total** | {t['num_statements']} | {t['covered_lines']} | {t['missing_lines']} | "
                 f"**{pct(t['covered_lines'], t['num_statements'])}** | "
                 f"{pct(t['covered_lines'] + t['covered_branches'], t['num_statements'] + t['num_branches'])} |")
    lines += ["", "Line + branch is the figure coverage.py prints as `Cover`: statements and "
              "branches taken together. Branch details are in `Branch_Coverage_Report.md`.", "",
              "## By file", "",
              "| File | Statements | Not run | Line coverage | Lines not run |",
              "| --- | --- | --- | --- | --- |"]
    for _, names in scopes(files):
        for name in names:
            s = files[name]["summary"]
            missing = ", ".join(ranges(files[name])) or "-"
            lines.append(f"| `{name}` | {s['num_statements']} | {s['missing_lines']} | "
                         f"{pct(s['covered_lines'], s['num_statements'])} | {missing} |")
    lines += ["", "## Lines not run", ""]
    for _, names in scopes(files):
        for name in names:
            groups = runs(files[name])
            if not groups:
                continue
            code = source_lines(name)
            lines.append(f"**`{name}`**")
            lines.append("")
            for first, last in groups:
                where = f"line {first}" if first == last else f"lines {first}-{last}"
                lines.append(f"- {where}: {snippet(code, first)}")
            lines.append("")
    return "\n".join(lines)


def runs(data):
    """Missing statements grouped into (first, last) runs of consecutive statements."""
    missing = set(data["missing_lines"])
    statements = sorted(set(data["executed_lines"]) | missing)
    groups = []
    for line in statements:
        if line in missing:
            if groups and groups[-1][2]:
                groups[-1][1] = line
            else:
                groups.append([line, line, True])
        elif groups:
            groups[-1][2] = False
    return [(first, last) for first, last, _ in groups]


def ranges(data):
    return [f"{a}" if a == b else f"{a}-{b}" for a, b in runs(data)]


def branch_report(cov, build):
    files = cov["files"]
    lines = coverage_header("Branch Coverage Report",
                            "which decisions (if/else, loops, early returns) the automated tests "
                            "take both ways.", build)
    lines += ["## Summary", "",
              "| Scope | Branches | Taken | Not taken | Branch coverage | Lines with a branch not taken |",
              "| --- | --- | --- | --- | --- | --- |"]
    every = []
    for label, names in scopes(files):
        every += names
        t = totals(files, names)
        lines.append(f"| {label} | {t['num_branches']} | {t['covered_branches']} | "
                     f"{t['missing_branches']} | {pct(t['covered_branches'], t['num_branches'])} | "
                     f"{t['num_partial_branches']} partly taken |")
    t = totals(files, every)
    lines.append(f"| **Total** | {t['num_branches']} | {t['covered_branches']} | "
                 f"{t['missing_branches']} | **{pct(t['covered_branches'], t['num_branches'])}** | "
                 f"{t['num_partial_branches']} partly taken |")
    lines += ["", "A branch is one way out of a decision: an `if` has two (true and false), a "
              "loop has two (run the body again, or leave). \"Partly taken\" lines ran, but "
              "only one way. Branches inside lines that never ran count as not taken.", "",
              "## By file", "",
              "| File | Branches | Taken | Not taken | Branch coverage |",
              "| --- | --- | --- | --- | --- |"]
    for _, names in scopes(files):
        for name in names:
            s = files[name]["summary"]
            lines.append(f"| `{name}` | {s['num_branches']} | {s['covered_branches']} | "
                         f"{s['missing_branches']} | {pct(s['covered_branches'], s['num_branches'])} |")
    lines += ["", "## Branches not taken", "",
              "Each entry is the line with the decision and the way out the tests never took. "
              "\"Exit\" means leaving the function (or the script) from that line.", ""]
    for _, names in scopes(files):
        for name in names:
            missing = files[name]["missing_branches"]
            if not missing:
                continue
            code = source_lines(name)
            not_run = set(files[name]["missing_lines"])
            lines += [f"**`{name}`**", ""]
            for start, end in missing:
                target = "exit" if end < 0 else f"line {end}"
                note = " (the line itself never ran)" if start in not_run else ""
                lines.append(f"- line {start} → {target}{note}: {snippet(code, start)}")
            lines.append("")
    return "\n".join(lines)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        code, output, junit, cov_json = run_tests(Path(tmp))
        if not junit.exists() or not cov_json.exists():
            print(output)
            sys.exit(code or 1)
        files = test_files()
        tests, seconds = read_junit(junit, files)
        cov = json.loads(cov_json.read_text())

    build = build_info()
    (OUT / "results").mkdir(parents=True, exist_ok=True)
    (OUT / "results" / "pytest-coverage-run.txt").write_text(output)
    (OUT / "Unit_Test_Report.md").write_text(unit_report(tests, seconds, files, build) + "\n")
    (OUT / "Code_Coverage_Report.md").write_text(line_report(cov, build) + "\n")
    (OUT / "Branch_Coverage_Report.md").write_text(branch_report(cov, build) + "\n")
    passed = sum(1 for t in tests if t["result"] == "passed")
    t = cov["totals"]
    print(f"{passed} of {len(tests)} tests passed; line coverage "
          f"{pct(t['covered_lines'], t['num_statements'])}, branch coverage "
          f"{pct(t['covered_branches'], t['num_branches'])}. Reports in docs/reports/.")
    sys.exit(code)


if __name__ == "__main__":
    main()
